import "server-only";
import { randomUUID } from "node:crypto";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";

/**
 * Where uploaded files live. With BLOB_READ_WRITE_TOKEN (a private Vercel Blob store) files go
 * to Vercel Blob and are only reachable through this app's download route. Without it,
 * development keeps them in .data/uploads; production refuses rather than losing files.
 */
// Vercel functions accept request bodies up to 4.5 MB.
export const MAX_FILE_BYTES = 4 * 1024 * 1024;

/** Allowed types: documents, images, spreadsheets, archives. Never HTML/SVG/scripts. */
export const ALLOWED_TYPES: Record<string, string> = {
  "application/pdf": ".pdf",
  "image/png": ".png",
  "image/jpeg": ".jpg",
  "image/webp": ".webp",
  "image/gif": ".gif",
  "text/plain": ".txt",
  "text/csv": ".csv",
  "application/zip": ".zip",
  "application/msword": ".doc",
  "application/vnd.openxmlformats-officedocument.wordprocessingml.document": ".docx",
  "application/vnd.ms-excel": ".xls",
  "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet": ".xlsx",
  "application/vnd.ms-powerpoint": ".ppt",
  "application/vnd.openxmlformats-officedocument.presentationml.presentation": ".pptx",
};

export const storageConfigured = () => Boolean(process.env.BLOB_READ_WRITE_TOKEN);
const LOCAL_DIR = path.join(process.cwd(), ".data", "uploads");

export async function putFile(workspaceId: string, content: Buffer, contentType: string) {
  const key = `${workspaceId}/${randomUUID()}${ALLOWED_TYPES[contentType] ?? ""}`;
  if (storageConfigured()) {
    const { put } = await import("@vercel/blob");
    const blob = await put(key, content, { access: "private", contentType, addRandomSuffix: true });
    return `blob:${blob.pathname}`;
  }
  if (process.env.NODE_ENV === "production") throw new Error("File storage is not configured (BLOB_READ_WRITE_TOKEN).");
  const file = path.join(LOCAL_DIR, key);
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, content);
  return `local:${key}`;
}

export async function readStoredFile(storageKey: string): Promise<ReadableStream | Buffer | null> {
  if (storageKey.startsWith("blob:")) {
    const { get } = await import("@vercel/blob");
    const res = await get(storageKey.slice(5), { access: "private" });
    return res?.stream ?? null;
  }
  if (storageKey.startsWith("local:")) {
    const file = path.join(LOCAL_DIR, storageKey.slice(6));
    // Keys are generated by putFile; refuse anything that escapes the uploads folder.
    if (!file.startsWith(LOCAL_DIR + path.sep)) return null;
    return readFile(file).catch(() => null);
  }
  return null;
}

export async function deleteStoredFile(storageKey: string) {
  if (storageKey.startsWith("blob:")) {
    const { del } = await import("@vercel/blob");
    await del(storageKey.slice(5));
  } else if (storageKey.startsWith("local:")) {
    const file = path.join(LOCAL_DIR, storageKey.slice(6));
    if (file.startsWith(LOCAL_DIR + path.sep)) await rm(file, { force: true });
  }
}

/**
 * The real type of an upload from its first bytes, so a renamed .html cannot pass as a .pdf.
 * Falls back to the browser's claim only for plain-text types, which have no signature.
 */
export function sniffType(head: Buffer, claimed: string) {
  const b = head;
  if (b.subarray(0, 5).toString() === "%PDF-") return "application/pdf";
  if (b[0] === 0x89 && b.subarray(1, 4).toString() === "PNG") return "image/png";
  if (b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff) return "image/jpeg";
  if (b.subarray(0, 4).toString() === "RIFF" && b.subarray(8, 12).toString() === "WEBP") return "image/webp";
  if (b.subarray(0, 3).toString() === "GIF") return "image/gif";
  if (b[0] === 0x50 && b[1] === 0x4b) {
    // ZIP container: also .docx / .xlsx / .pptx.
    return claimed.startsWith("application/vnd.openxmlformats") || claimed === "application/zip" ? claimed : "application/zip";
  }
  if (b[0] === 0xd0 && b[1] === 0xcf && b[2] === 0x11 && b[3] === 0xe0) {
    return ["application/msword", "application/vnd.ms-excel", "application/vnd.ms-powerpoint"].includes(claimed) ? claimed : null;
  }
  if (claimed === "text/plain" || claimed === "text/csv") {
    const text = b.toString("utf8").toLowerCase();
    return /<(script|html|svg|iframe)/.test(text) ? null : claimed;
  }
  return null;
}
